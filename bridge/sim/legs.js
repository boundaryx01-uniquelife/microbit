const clamp = (v, a, b) => Math.max(a, Math.min(b, v));

function curveByHeight(points, h) {
  if (h <= points[0][0]) return [points[0][1], points[0][2]];
  const last = points[points.length - 1];
  if (h >= last[0]) return [last[1], last[2]];
  for (let i = 0; i < points.length - 1; i++) {
    const a = points[i], b = points[i + 1];
    if (h >= a[0] && h <= b[0]) { const r = b[0] === a[0] ? 0 : (h - a[0]) / (b[0] - a[0]); return [a[1] + (b[1] - a[1]) * r, a[2] + (b[2] - a[2]) * r]; }
  }
  return [last[1], last[2]];
}
function idw(h, r, k) {   // 공식과 같은 역거리 가중 보간(지수 3, 높이 18·발끝 32로 정규화)
  let tot = 0, ws = 0;
  for (const s of SAMPLES) {
    if (s[0] === h && s[1] === r) return s[k];
    const d = Math.hypot((h - s[0]) / 18, (r - s[1]) / 32), w = 1 / Math.pow(d, 3);
    tot += s[k] * w; ws += w;
  }
  return tot / ws;
}
// 다리 높이(20~90)·발끝(-90~90) → [어깨, 무릎] (공식 시뮬레이터와 같은 결과)
const cache = new Map();
export function lengthToAngles(height, reach) {
  const h = clamp(Math.round(height), 20, 90), r = clamp(Math.round(reach), -90, 90);
  const key = h * 1000 + r;
  if (cache.has(key)) return cache.get(key);
  const sp = SPECIAL_REACH_CURVES[String(r)];
  let out;
  if (sp) { const [s, e] = curveByHeight(sp, h); out = [clamp(Math.round(s), -90, 90), clamp(Math.round(e), -90, 70)]; }
  else out = [clamp(Math.round(idw(h, r, 2)), -90, 90), clamp(Math.round(idw(h, r, 3)), -90, 70)];
  cache.set(key, out);
  return out;
}

// 어깨·무릎(도) → 렌더링용 값. sh·kn: 라디안(아래 기준, 앞 +, kn은 윗다리에 대한 상대각), h: 엉덩이에서 발까지 높이(cm), fx: 발 앞뒤(cm)
export function legFromAngles(shDeg, elDeg) {
  const p1 = shDeg * Math.PI / 180, p2 = (shDeg + elDeg + 90) * Math.PI / 180;
  const fx = GEOM.upper * Math.sin(p1) + GEOM.lower * Math.sin(p2);
  const h = GEOM.upper * Math.cos(p1) + GEOM.lower * Math.cos(p2);
  return { sh: p1, kn: p2 - p1, h, fx, shDeg, elDeg };
}
